#!/usr/bin/env node
// Writes web/config.js from environment variables at build time (Netlify → Site settings → Environment variables).
//   SUPABASE_URL       e.g. https://abcdefghijklmnop.supabase.co
//   SUPABASE_ANON_KEY  the project's anon/publishable key (safe for browsers; RLS protects the data)
// If they're missing, the site still deploys in local-only mode (progress stays in the browser).
const fs = require("fs");
const path = require("path");
const url = (process.env.SUPABASE_URL || "").trim().replace(/\/+$/, "");
const key = (process.env.SUPABASE_ANON_KEY || "").trim();
if (url && !/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) {
  console.error(`SUPABASE_URL looks wrong: "${url}" (expected https://<project-ref>.supabase.co)`);
  process.exit(1);
}
if (/service_role/.test(key) || /^sb_secret_/.test(key)) {
  console.error("Refusing to publish a SERVICE ROLE / secret key to the browser. Use the anon (publishable) key.");
  process.exit(1);
}
// ALLOW_GUEST=false hides "Continue without an account" so the app requires sign-in.
const allowGuest = !/^(false|0|no|off)$/i.test((process.env.ALLOW_GUEST || "true").trim());
const out = `// Generated by tools/write-config.js — do not edit by hand.\nwindow.SECPLUS_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseAnonKey: key, allowGuest })};\n`;
fs.writeFileSync(path.join(__dirname, "..", "web", "config.js"), out);
console.log(url && key ? `config.js written for ${url} (guest access: ${allowGuest ? "on" : "off"})` : "config.js written in LOCAL-ONLY mode (no Supabase env vars set)");
